import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const snapshots = {
    vllmV0240: "runtime-defaults/vllm/v0.24.0.json",
    llamaCppB9860: "runtime-defaults/llama-cpp/b9860.json",
};
const outputPath = resolve(
    root,
    "packages/core/src/generated/runtimeDefaults.generated.ts",
);

const entries = await Promise.all(
    Object.entries(snapshots).map(async ([name, relativePath]) => {
        const raw = await readFile(resolve(root, relativePath), "utf8");
        return `export const ${name} = ${raw.trim()} satisfies RuntimeSnapshot;`;
    }),
);

const output = `// This file is generated by scripts/generate-runtime-defaults.mjs.
// Edit runtime-defaults/*.json, then run npm run generate:runtime-defaults.

import type { RuntimeSnapshot } from "../types.js";

${entries.join("\n\n")}
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output);
